from abc import ABC,abstractmethod
class MarketDataProvider(ABC):
    @abstractmethod
    async def connect(self):...
    @abstractmethod
    async def disconnect(self):...
    @abstractmethod
    async def subscribe(self,keys,mode):...
    @abstractmethod
    async def unsubscribe(self,keys):...
    @abstractmethod
    async def get_quotes(self,keys):...
    @abstractmethod
    async def get_historical_candles(self,key,interval,start,end):...
    @abstractmethod
    async def get_intraday_candles(self,key,interval):...
    @abstractmethod
    async def get_instruments(self):...
    @abstractmethod
    async def health_check(self):...
class ProviderError(RuntimeError):
    def __init__(self,code='PROVIDER_UNAVAILABLE'):super().__init__(code);self.code=code
