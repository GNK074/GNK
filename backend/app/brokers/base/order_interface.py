from typing import Protocol
class OrderAdapter(Protocol):
    def place_order(self,validated_intent:dict)->dict: ...
    def modify_order(self,broker_order_id:str,changes:dict)->dict: ...
    def cancel_order(self,broker_order_id:str)->dict: ...
    def order_status(self,broker_order_id:str)->dict: ...
# Contract only. No live execution implementation is registered.
